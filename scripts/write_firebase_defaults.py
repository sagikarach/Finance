#!/usr/bin/env python3
"""Bake the Firebase project config into the build, so a new user can sign up
right away with nothing to configure.

Writes finance/firebase_defaults_local.py (git-ignored) from the environment:
  FINANCE_FIREBASE_API_KEY, FINANCE_FIREBASE_PROJECT_ID
(in CI these come from repo secrets of the same name).

The Firebase *web API key* is not a secret — it identifies the project and
ships inside every client (the mobile app has it too); data is protected by
firestore.rules. It is kept out of git only to avoid key-scanner noise.

- Env vars set     → (re)write the file.
- Env vars missing → keep an existing local file; in CI with none, fail the
  build rather than ship an app nobody can log in to.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "finance" / "firebase_defaults_local.py"


def main() -> int:
    key = os.environ.get("FINANCE_FIREBASE_API_KEY", "").strip()
    project = os.environ.get("FINANCE_FIREBASE_PROJECT_ID", "").strip()
    if key and project:
        TARGET.write_text(
            "# Generated by scripts/write_firebase_defaults.py — do not commit.\n"
            f"API_KEY = {key!r}\nPROJECT_ID = {project!r}\n",
            encoding="utf-8",
        )
        print(f"Firebase config written for project {project}")
        return 0
    if TARGET.exists():
        print("Using existing finance/firebase_defaults_local.py")
        return 0
    msg = (
        "Firebase config missing: set FINANCE_FIREBASE_API_KEY and "
        "FINANCE_FIREBASE_PROJECT_ID (repo secrets in CI). Without it the app "
        "can't sign anyone in."
    )
    if os.environ.get("CI"):
        print(f"ERROR: {msg}", file=sys.stderr)
        return 1
    print(f"WARNING: {msg}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
